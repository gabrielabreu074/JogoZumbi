    def desenhar(self):

        for linha in range(len(self.mapa)):

            for coluna in range(len(self.mapa[linha])):

                x = coluna * self.tamanho_tile - self.camera.camera_x
                y = linha * self.tamanho_tile - self.camera.camera_y

                if self.mapa[linha][coluna] == 0:
                    cor = (40, 40, 40)

                else:
                    cor = (70, 140, 70)

                pygame.draw.rect(
                    self.tela,
                    cor,
                    (x, y, self.tamanho_tile, self.tamanho_tile)
                )
                if self.mapa[linha][coluna] == 0:
                    pygame.draw.rect(self.tela, (0,0,0), (x + 20, y, 10, 10))
                    pygame.draw.rect(self.tela, (115,130,130), (x + 3, y + 3, 34, 34), width = 3)
                else:
                    pygame.draw.rect(self.tela, (0,100,0), (x + 1, y + 5, 34, 34))
                    pygame.draw.rect(self.tela, (0,190,0), (x + 3, y + 7, 30, 30), width = 3)

    def pode_andar(self, retangulo):
        esquerda = retangulo.left // self.tamanho_tile
        direita = (retangulo.right - 1) // self.tamanho_tile
        cima = retangulo.top // self.tamanho_tile
        baixo = (retangulo.bottom - 1) // self.tamanho_tile

        for linha in range (cima, baixo + 1):

            for coluna in range (esquerda, direita + 1):
                if self.mapa[linha][coluna] == 0:
                    return False

        return True